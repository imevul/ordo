import { createServer, type Server } from 'node:http';
import type { AddressInfo } from 'node:net';

export interface ForgeRequest {
  method: string;
  path: string;
  headers: Record<string, string | string[] | undefined>;
  body: unknown;
}

type Reply = { status?: number; body?: unknown; headers?: Record<string, string> } | undefined;
type Handler = (req: ForgeRequest) => Reply | Promise<Reply>;

/** A stand-in for forge and chat APIs: answers from registered handlers, logs every call. */
export async function startMockForge() {
  const routes = new Map<string, Handler>();
  const prefixes: [string, Handler][] = [];
  const log: ForgeRequest[] = [];
  const server: Server = createServer(async (req, res) => {
    let raw = '';
    for await (const chunk of req) raw += chunk;
    const url = new URL(req.url!, 'http://x');
    const entry: ForgeRequest = {
      method: req.method!,
      path: url.pathname + url.search,
      headers: req.headers,
      body: raw ? JSON.parse(raw) : null,
    };
    log.push(entry);
    const handler =
      routes.get(`${req.method} ${url.pathname}`) ??
      prefixes.find(([p]) => `${req.method} ${url.pathname}`.startsWith(p))?.[1];
    const out =
      (await handler?.(entry)) ??
      (handler ? { status: 200, body: {} } : { status: 404, body: { message: 'Not Found' } });
    res
      .writeHead(out.status ?? 200, { 'content-type': 'application/json', ...out.headers })
      .end(JSON.stringify(out.body ?? {}));
  });
  await new Promise<void>((r) => server.listen(0, '127.0.0.1', () => r()));
  const url = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  return {
    url,
    log,
    on(method: string, path: string, handler: Handler | unknown) {
      routes.set(
        `${method} ${path}`,
        typeof handler === 'function' ? (handler as Handler) : () => ({ body: handler }),
      );
    },
    /** Answers every path starting with `prefix` (ids generated by the client, like Matrix txn ids). */
    onPrefix(method: string, prefix: string, handler: Handler | unknown) {
      prefixes.push([
        `${method} ${prefix}`,
        typeof handler === 'function' ? (handler as Handler) : () => ({ body: handler }),
      ]);
    },
    calls: (method: string, path: string) =>
      log.filter((r) => r.method === method && r.path.split('?')[0] === path),
    close: () => new Promise<void>((r) => server.close(() => r())),
  };
}
